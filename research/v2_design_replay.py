"""Design evidence for recipe v2 from the saved hardware counts (no new jobs, run folders unchanged).

Replays the recipe-v1 data of hardware rounds 1 and 2 (ibm_fez, scales 1/3/5, readout-corrected) with:
  recipe v1          frozen rule (exp guard falls back to linear)
  v1 data + clip     the v2 rule (same branch test, then clip to the physical range) on the same data

This isolates change 3 (clipping) on real hardware data. Changes 1 and 2 (twirling, scales 1/1.5/2) need new
data and are tested on the v2 held-out circuits (PREREGISTRATION.md Part F). These 8 circuits are SEEN data:
they motivated v2 and cannot be used to claim it works.

    .venv/Scripts/python v2_design_replay.py
"""

from __future__ import annotations

import statistics
import sys
import warnings
from pathlib import Path

import recipe
import recipe_v2
import runlog
from hardware import HW_CIRCUITS
from mitigation import SCALE_FACTORS, SCALE_KEYS, apply_readout_correction, confusion_matrix, extrapolate, tasks
from baseline import to_probs

warnings.filterwarnings("ignore")
HERE = Path(__file__).parent
ROUNDS = {"round 1": "20261124-104424_hardware-round1", "round 2": "20261124-105849_hardware-round2"}


def main() -> None:
    by_name = {t.name: t for t in tasks("train") + tasks("test") if t.name in HW_CIRCUITS}
    lines = ["# Recipe v2 design replay on saved hardware counts", "",
             "Generated by `python v2_design_replay.py`. Data: the recipe-v1 jobs of hardware rounds 1 and 2 on "
             "`ibm_fez` (scales 1/3/5, readout-corrected). **Seen data**: it motivated v2 and is not evidence that v2 "
             "works. Only the clipping change can be replayed here; twirling and scales 1/1.5/2 need new data.", "",
             "| Round | Circuit | Exact | Values at scales 1/3/5 | Recipe v1 | Branch | v1 data + clip | Branch | "
             "RMSE v1 | RMSE clip |", "|---|---|---|---|---|---|---|---|---|---|"]
    summary = {}
    for label, run in ROUNDS.items():
        results = runlog.read_json(HERE / "results" / "runs" / run / "results.json")
        counts = results["recipe"]["counts"]
        errs_v1, errs_clip = [], []
        for name in HW_CIRCUITS:
            task = by_name[name]
            sq_v1, sq_clip = [], []
            for o in task.observables:
                keys = counts[name][o.basis]
                zero, one = to_probs(keys["cal0"]), to_probs(keys["cal1"])
                n = len(next(iter(zero)))
                matrix = confusion_matrix(zero, one, n)
                vals = [o.value(apply_readout_correction(to_probs(keys[k]), matrix, n)) for k in SCALE_KEYS]
                est = {f"readout_zne_{f}": extrapolate(f, vals, o)[0] for f in ("linear", "expg")}
                v1, b1 = recipe.estimate({}, o, est, vals)
                v2, b2 = recipe_v2.estimate(o, list(SCALE_FACTORS), vals)
                sq_v1.append((v1 - o.exact) ** 2)
                sq_clip.append((v2 - o.exact) ** 2)
                if len(task.observables) == 1:
                    lines.append(f"| {label} | {name} | {o.exact:+.3f} | {' / '.join(f'{v:.3f}' for v in vals)} | "
                                 f"{v1:+.3f} | {b1} | {v2:+.3f} | {b2} | |")
            r1, r2 = statistics.mean(sq_v1) ** 0.5, statistics.mean(sq_clip) ** 0.5
            if len(task.observables) == 1:
                lines[-1] = lines[-1][: -len(" | |")] + f" | {r1:.4f} | {r2:.4f} |"
            else:
                lines.append(f"| {label} | {name} | ({len(task.observables)} observables) | | | | | | {r1:.4f} | {r2:.4f} |")
            errs_v1.append(r1)
            errs_clip.append(r2)
        summary[label] = (errs_v1, errs_clip)
    lines += ["", "| Round | Mean RMSE recipe v1 | Mean RMSE v1 data + clip | Circuits where clip changed the result |",
              "|---|---|---|---|"]
    for label, (a, b) in summary.items():
        changed = sum(abs(x - y) > 1e-12 for x, y in zip(a, b))
        lines.append(f"| {label} | {statistics.mean(a):.4f} | {statistics.mean(b):.4f} | {changed} of {len(a)} |")
    out = HERE / "results" / "v2_design_replay.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
