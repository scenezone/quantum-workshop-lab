"""Per-job QPU usage of the hardware runs, for cost planning.

Reads the saved results.json of every hardware run (never re-contacts IBM, never changes the run folders) and
writes results/hardware_usage.md with, for every job: method, role, job ID, shots, the QPU seconds IBM charged
(`metrics()["usage"]["qpu_charge_time_seconds"]`), the value `job.usage()` returned at run time, RUs,
circuit execution time and wall time.

Why the charged seconds: `job.usage()` returned 0 for two short jobs (the smoke Sampler job and the recipe's
readout-calibration job) whose IBM metrics show 2 s and 7 s charged, and whose RUs are non-zero.

    .venv/Scripts/python hardware_usage.py [--usd-per-minute 96]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import runlog

HERE = Path(__file__).parent
RUNS = HERE / "results" / "runs"
METHOD_ORDER = ("none", "recipe", "ibm_rl1", "ibm_rl2")
LABEL = {"none": "none", "recipe": "recipe", "ibm_rl1": "IBM level 1", "ibm_rl2": "IBM level 2"}


def role(method: str, index: int, job: dict) -> str:
    if method == "recipe":
        return "Sampler, folded circuits (scales 1/3/5)" if index == 0 else "Sampler, readout calibration"
    if method == "none":
        return "Sampler"
    return f"Estimator, resilience_level {job.get('resilience_level', '?')}"


def charged(job: dict) -> float | None:
    usage = (job.get("metrics") or {}).get("usage") or {}
    value = usage.get("qpu_charge_time_seconds")
    return None if value is None else float(value)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--usd-per-minute", type=float, default=96.0,
                        help="Pay-As-You-Go price used for the cost column (IBM pricing page, checked 24 Nov 2026)")
    args = parser.parse_args()
    rate = args.usd_per_minute / 60

    runs = sorted(p for p in RUNS.iterdir() if p.is_dir() and "_hardware-" in p.name and "dryrun" not in p.name
                  and (p / "results.json").exists())
    lines = [
        "# Hardware usage per job",
        "",
        "Generated by `python hardware_usage.py` from the saved `results.json` of each run (run folders unchanged).",
        "",
        "- **Charged s** = `metrics()[\"usage\"][\"qpu_charge_time_seconds\"]`, the QPU time IBM bills. Use this column.",
        "- **usage() s** = what `job.usage()` returned at run time. It showed 0 for two short jobs that were in fact "
        "charged 2 s and 7 s, so it under-counts. Fixed in `hardware.py` for future runs.",
        "- **Exec s** = `circuits_execution_time_ns`, the time spent executing circuits (part of the charged time).",
        "- **Wall s** = submit to result on our side, including queue. Not billed.",
        f"- **Cost** = charged s × ${rate:.2f} (Pay-As-You-Go ${args.usd_per_minute:g}/min, per IBM's pricing page on "
        "24 Nov 2026; check the current price before budgeting). On the Open Plan these jobs cost nothing.",
        "",
    ]
    grand = {"s": 0.0, "ru": 0.0}
    per_method_rounds: dict[str, list[tuple[float, float]]] = {}
    for run in runs:
        results = runlog.read_json(run / "results.json")
        lines += [f"## `{run.name}`", "",
                  "| Method | Job | Job ID | Shots per PUB | Charged s | usage() s | RUs | Exec s | Wall s | Cost (USD) |",
                  "|---|---|---|---|---|---|---|---|---|---|"]
        run_s = run_ru = 0.0
        for method in [m for m in METHOD_ORDER if m in results]:
            m_s = m_ru = 0.0
            for i, job in enumerate(results[method].get("jobs", [])):
                s, ru = charged(job), job.get("rus")
                exec_ns = (job.get("metrics") or {}).get("circuits_execution_time_ns")
                m_s += s or 0.0
                m_ru += ru or 0.0
                lines.append(
                    f"| {LABEL[method]} | {role(method, i, job)} | `{job['job_id']}` | {job.get('shots') or 'n/a'} | "
                    f"{s:g} | {job.get('quantum_seconds')} | {ru:.4f} | "
                    f"{'n/a' if exec_ns is None else f'{exec_ns / 1e9:.1f}'} | {job.get('wall_s', 0):.0f} | "
                    f"{(s or 0) * rate:.2f} |")
            if len(results[method].get("jobs", [])) > 1:
                lines.append(f"| **{LABEL[method]} total** | | | | **{m_s:g}** | | **{m_ru:.4f}** | | | "
                             f"**{m_s * rate:.2f}** |")
            if "smoke" not in run.name:
                per_method_rounds.setdefault(method, []).append((m_s, m_ru))
            run_s += m_s
            run_ru += m_ru
        lines += ["", f"Run total: **{run_s:g} s charged, {run_ru:.4f} RU** (≈ ${run_s * rate:.2f} at Pay-As-You-Go).",
                  ""]
        grand["s"] += run_s
        grand["ru"] += run_ru

    lines += ["## Per method, per round (cost planning)", "",
              "| Method | Charged s per round | RUs per round | Cost per round (USD) | Rounds measured |",
              "|---|---|---|---|---|"]
    round_s = 0.0
    for method in [m for m in METHOD_ORDER if m in per_method_rounds]:
        vals = per_method_rounds[method]
        s = sum(v[0] for v in vals) / len(vals)
        ru = sum(v[1] for v in vals) / len(vals)
        spread = "identical" if len({v for v in vals}) == 1 else "differ"
        round_s += s
        lines.append(f"| {LABEL[method]} | {s:g} | {ru:.4f} | {s * rate:.2f} | {len(vals)} ({spread}) |")
    lines += [f"| **All four methods** | **{round_s:g}** | | **{round_s * rate:.2f}** | |", "",
              f"All hardware runs so far: **{grand['s']:g} s charged, {grand['ru']:.4f} RU** "
              f"(≈ ${grand['s'] * rate:.2f} if it had been Pay-As-You-Go).", ""]
    out = HERE / "results" / "hardware_usage.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(lines))
    print(f"\nWrote {out}")


if __name__ == "__main__":
    main()
