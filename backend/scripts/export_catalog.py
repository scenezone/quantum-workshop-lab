"""Write the backend's experiment, gate, noise, and challenge catalog for the frontend.

Run from backend/:  python scripts/export_catalog.py
CI fails when frontend/src/types/catalog.generated.ts is out of date.
"""

import json
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
if str(BACKEND) not in sys.path:
    sys.path.insert(0, str(BACKEND))

from app.content.challenges import EXPERIMENT_CHALLENGE_IDS  # noqa: E402
from app.content.curriculum import ExperimentId  # noqa: E402
from app.quantum.catalog import (  # noqa: E402
    ANGLE_LIMIT,
    CUSTOM_GATES,
    MAX_CUSTOM_GATES,
    MAX_CUSTOM_QUBITS,
    MEASUREMENT_BASES,
    noise_profile_catalog,
)

OUTPUT = BACKEND.parent / "frontend" / "src" / "types" / "catalog.generated.ts"


def _value(value) -> str:
    return json.dumps(value, indent=2, ensure_ascii=False)


def render() -> str:
    gates = {
        name: {key: spec[key] for key in ("qubits", "params", "symbol", "label")}
        for name, spec in CUSTOM_GATES.items()
    }
    sections = [
        "// Generated by backend/scripts/export_catalog.py. Do not edit by hand.",
        f"export const EXPERIMENT_IDS = {_value([item.value for item in ExperimentId])} as const;",
        f"export const CUSTOM_GATES = {_value(gates)} as const;",
        f"export const MAX_CUSTOM_QUBITS = {MAX_CUSTOM_QUBITS};",
        f"export const MAX_CUSTOM_GATES = {MAX_CUSTOM_GATES};",
        f"export const ANGLE_LIMIT = {ANGLE_LIMIT!r};",
        f"export const MEASUREMENT_BASES = {_value(list(MEASUREMENT_BASES))} as const;",
        f"export const NOISE_PROFILES = {_value(noise_profile_catalog())} as const;",
        f"export const EXPERIMENT_CHALLENGE_IDS = {_value(list(EXPERIMENT_CHALLENGE_IDS))} as const;",
    ]
    return "\n\n".join(sections) + "\n"


if __name__ == "__main__":
    OUTPUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT}")
